import React, { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { FolderPlus } from 'lucide-react';
import PageHeader from '../../components/layout/PageHeader';
import DataTable from '../../components/ui/DataTable';
import FilterBar from '../../components/ui/FilterBar';
import Input from '../../components/ui/Input';
import Select from '../../components/ui/Select';
import Button from '../../components/ui/Button';
import StatusBadge from '../../components/ui/StatusBadge';
import Skeleton from '../../components/ui/Skeleton';
import ErrorState from '../../components/ui/ErrorState';
import { useToast } from '../../components/ui/Toast';
import { useAsync } from '../../lib/useAsync';
import * as fraudApi from '../../api/fraud';
import { formatDate } from '../../lib/format';
import {
  ALERT_STATUSES,
  RISK_SEVERITIES,
  RISK_RULES,
  RISK_RULE_LABELS,
} from '../../lib/constants';

export default function AlertsListPage() {
  const navigate = useNavigate();
  const { showToast } = useToast();

  const [page, setPage] = useState(1);
  const [status, setStatus] = useState('');
  const [rule, setRule] = useState('');
  const [severity, setSeverity] = useState('');
  const [from, setFrom] = useState('');
  const [to, setTo] = useState('');

  const [selectedAlertIds, setSelectedAlertIds] = useState([]);
  const [creatingCase, setCreatingCase] = useState(false);

  const {
    data: alertsData,
    loading,
    error,
    reload,
  } = useAsync(
    () =>
      fraudApi.listAlerts({
        status: status || undefined,
        rule: rule || undefined,
        severity: severity || undefined,
        from: from || undefined,
        to: to || undefined,
        page,
        pageSize: 10,
      }),
    [page, status, rule, severity, from, to]
  );

  const handleCreateCaseFromSelected = async () => {
    if (selectedAlertIds.length === 0) return;
    setCreatingCase(true);
    try {
      const newCase = await fraudApi.createCase({ alertIds: selectedAlertIds });
      showToast(`Case ${newCase.case_no} created with ${selectedAlertIds.length} alerts.`, 'success');
      setSelectedAlertIds([]);
      navigate(`/fraud/cases/${newCase.case_id}`);
    } catch (err) {
      showToast(err.message || 'Could not create case.', 'error');
    } finally {
      setCreatingCase(false);
    }
  };

  const handleResetFilters = () => {
    setStatus('');
    setRule('');
    setSeverity('');
    setFrom('');
    setTo('');
    setPage(1);
  };

  const columns = [
    {
      key: 'alert_id',
      header: 'Alert ID',
      render: (r) => <span className="font-mono text-12 font-medium text-text">#{r.alert_id}</span>,
    },
    {
      key: 'rule_code',
      header: 'Rule',
      render: (r) => <span>{RISK_RULE_LABELS[r.rule_code] || r.rule_code}</span>,
    },
    {
      key: 'severity',
      header: 'Severity',
      render: (r) => <StatusBadge status={r.severity} />,
    },
    {
      key: 'wallet_no',
      header: 'Wallet number',
      render: (r) => <span className="font-mono text-12 text-text">{r.wallet_no}</span>,
    },
    {
      key: 'window',
      header: 'Inspection window',
      render: (r) => (
        <span className="text-12 text-text-muted">
          {formatDate(r.window_start)} – {formatDate(r.window_end)}
        </span>
      ),
    },
    {
      key: 'status',
      header: 'Status',
      render: (r) => <StatusBadge status={r.status} />,
    },
    {
      key: 'created_at',
      header: 'Created at',
      align: 'right',
      render: (r) => <span className="text-12 text-text-muted">{formatDate(r.created_at)}</span>,
    },
  ];

  return (
    <div className="space-y-6">
      <PageHeader
        title="Fraud risk alerts"
        subtitle="Automated alerts generated by velocity, structuring, and rapid in-out flow engines"
        action={
          selectedAlertIds.length > 0 && (
            <Button
              variant="primary"
              onClick={handleCreateCaseFromSelected}
              loading={creatingCase}
              loadingText="Creating case..."
            >
              <FolderPlus size={16} />
              <span>Create case from selected ({selectedAlertIds.length})</span>
            </Button>
          )
        }
      />

      <FilterBar onReset={handleResetFilters}>
        <Select
          value={status}
          onChange={(e) => {
            setStatus(e.target.value);
            setPage(1);
          }}
          className="w-32"
        >
          <option value="">All statuses</option>
          {Object.entries(ALERT_STATUSES).map(([k, v]) => (
            <option key={k} value={v}>
              {v}
            </option>
          ))}
        </Select>

        <Select
          value={rule}
          onChange={(e) => {
            setRule(e.target.value);
            setPage(1);
          }}
          className="w-40"
        >
          <option value="">All rules</option>
          {Object.entries(RISK_RULES).map(([k, v]) => (
            <option key={k} value={v}>
              {RISK_RULE_LABELS[v] || v}
            </option>
          ))}
        </Select>

        <Select
          value={severity}
          onChange={(e) => {
            setSeverity(e.target.value);
            setPage(1);
          }}
          className="w-32"
        >
          <option value="">All severities</option>
          {Object.entries(RISK_SEVERITIES).map(([k, v]) => (
            <option key={k} value={v}>
              {v}
            </option>
          ))}
        </Select>

        <Input
          type="date"
          value={from}
          onChange={(e) => {
            setFrom(e.target.value);
            setPage(1);
          }}
          className="w-36"
        />

        <Input
          type="date"
          value={to}
          onChange={(e) => {
            setTo(e.target.value);
            setPage(1);
          }}
          className="w-36"
        />
      </FilterBar>

      {loading && !alertsData ? (
        <Skeleton variant="table" rows={6} />
      ) : error ? (
        <ErrorState
          error={error}
          title="Could not load fraud alerts"
          onRetry={reload}
        />
      ) : (
        <DataTable
          columns={columns}
          data={alertsData?.items || []}
          keyField="alert_id"
          selectable
          selectedKeys={selectedAlertIds}
          onSelectionChange={setSelectedAlertIds}
          onRowClick={(row) => navigate(`/fraud/alerts/${row.alert_id}`)}
          pagination={alertsData}
          onPageChange={(newPage) => setPage(newPage)}
          emptyMessage="No fraud alerts matched the filters."
        />
      )}
    </div>
  );
}
